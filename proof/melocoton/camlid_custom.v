(** ** The C library and the templates of the type *)

Section C_spec.

  Import melocoton.c_interop.notation melocoton.c_lang.proofmode.

  Context `{SI:indexT}.
  Context  {Σ : gFunctors}.
  Context `{!heapG_C Σ}.
  Context `{!invG Σ}.

  (** [~init:"initialize_ptr"]: [void initialize_ptr(int ** p)] allocates
      the memory of the C value *)
  Definition initialize_ptr_spec : protocol C_intf.val Σ :=
    !! (l : loc) (w : C_intf.val)
    {{ l ↦C w }}
      "initialize_ptr" with [ #C l ]
    {{ (q : loc), RETV (#C 0); l ↦C #C q ∗ q ↦C #C 0 }}.

  (** [void two(int i, int * p, int * q)] writes [i] in [*p] and [*q] *)
  Definition two_spec : protocol C_intf.val Σ :=
    !! (n : Z) (q1 q2 : loc) (v1 v2 : C_intf.val)
    {{ q1 ↦C v1 ∗ q2 ↦C v2 }}
      "two" with [ #C n; #C q1; #C q2 ]
    {{ RETV (#C 0); q1 ↦C #C n ∗ q2 ↦C #C n }}.

  (** [int to_int(int * p)] reads [*p] *)
  Definition to_int_spec : protocol C_intf.val Σ :=
    !! (n : Z) (q : loc) dq
    {{ q ↦C{dq} #C n }}
      "to_int" with [ #C q ]
    {{ RETV (#C n); q ↦C{dq} #C n }}.

  Definition lib_spec : protocol C_intf.val Σ :=
    initialize_ptr_spec ⊔ two_spec ⊔ to_int_spec.

End C_spec.

(** ** The stubs *)

Section Stubs.

  Import melocoton.c_interop.notation melocoton.c_lang.proofmode.

  Context `{SI:indexT}.
  Context `{!ffiG Σ}.

  (** {v
      static void camlid_c2ml(value * v, int * * c){
        *v = caml_alloc_custom(&camlid_cops,sizeof(int * ), 0, 1);
        *(((int * * ) Data_custom_val( *v))) = *c;
      }
      v} *)
  Definition camlid_c2ml (v c : expr) : expr :=
    (v <- caml_alloc_custom ( ) ;;
     Custom_contents ( *v ) := *c)%CE.

  (** {v
      extern value camlid_stub_two(intptr_t p){
        CAMLparam0();
        CAMLlocal3(ret, p_r, p_r1);
        int p1 = ((int) { 0 });
        int * p2 = ((int * ) { 0 });
        int * p3 = ((int * ) { 0 });
        p1 = (int)(p);
        initialize_ptr(&p2);
        initialize_ptr(&p3);
        two(p1, p2, p3);
        camlid_c2ml(&p_r, &p2);
        camlid_c2ml(&p_r1, &p3);
        ret = caml_alloc(2,0);
        Store_field(ret, 0, p_r);
        Store_field(ret, 1, p_r1);
      CAMLreturn(ret);
      }
      extern value camlid_stub_two_byte(value p){
        intptr_t p1;
        p1 = Int_val(p);
        return camlid_stub_two(p1);
      }
      v} *)
  Definition two_code (p : expr) : expr :=
    let: "p1" := Int_val (p) in
    CAMLlocal: "ret" in CAMLlocal: "p_r" in CAMLlocal: "p_r1" in
    let: "p2" := malloc (#1) in
    let: "p3" := malloc (#1) in
    "p2" <- #0 ;;
    "p3" <- #0 ;;
    (call: &"initialize_ptr" with ("p2")) ;;
    (call: &"initialize_ptr" with ("p3")) ;;
    (call: &"two" with ("p1", *"p2", *"p3")) ;;
    camlid_c2ml "p_r" "p2" ;;
    camlid_c2ml "p_r1" "p3" ;;
    "ret" <- caml_alloc (#2, #0) ;;
    Store_field ( *"ret", #0, *"p_r" ) ;;
    Store_field ( *"ret", #1, *"p_r1" ) ;;
    free ("p2", #1) ;;
    free ("p3", #1) ;;
    CAMLreturn: *"ret" unregistering [ "ret", "p_r", "p_r1" ].

  (** {v
      extern intptr_t camlid_stub_to_int(value p){
        intptr_t ures;
        int res;
        int * p1 = ((int * ) { 0 });
        p1 = *(((int * * ) Data_custom_val(p)));
        res = to_int(p1);
        ures = (intptr_t)(res);
        return ures;
      }
      extern value camlid_stub_to_int_byte(value p){
        intptr_t ures;
        value vres;
        ures = camlid_stub_to_int(p);
        vres = Val_int(ures);
        return vres;
      }
      v} *)
  Definition to_int_code (p : expr) : expr :=
    let: "p1" := Custom_contents (p) in
    let: "res" := (call: &"to_int" with ("p1")) in
    Val_int ("res").

  Definition two_prog : lang_prog C_lang :=
    {[ "caml_two" := Fun [BNamed "p"] (two_code "p") ]}.

  Definition to_int_prog : lang_prog C_lang :=
    {[ "caml_to_int" := Fun [BNamed "p"] (to_int_code "p") ]}.

  (** ** What OCaml sees *)

  (** [external two : int -> myptr * myptr]: two new custom blocks, each
      keeps alive the C memory of its C value *)
  Definition two_ml_spec : protocol ML_lang.val Σ :=
    !! (n : Z)
      {{ True }}
        "caml_two" with [ #ML n ]
      {{ (γ1 γ2 : lloc) (q1 q2 : loc),
         RETV ((#ML (ML_lang.LitForeign γ1), #ML (ML_lang.LitForeign γ2))%MLV);
         γ1 ↦foreign[Mut] (#C q1) ∗ q1 ↦C #C n ∗
         γ2 ↦foreign[Mut] (#C q2) ∗ q2 ↦C #C n }}.

  (** [external to_int : myptr -> int]: borrows the C value of the custom
      block *)
  Definition to_int_ml_spec : protocol ML_lang.val Σ :=
    !! (γ : lloc) (q : loc) (n : Z)
      {{ "Hγ" ∷ γ ↦foreign[Mut] (#C q) ∗ "Hq" ∷ q ↦C #C n }}
        "caml_to_int" with [ #ML (ML_lang.LitForeign γ) ]
      {{ RETV (#ML n); γ ↦foreign[Mut] (#C q) ∗ q ↦C #C n }}.

  Lemma to_int_correct :
    prims_proto to_int_ml_spec ⊔ lib_spec
    ||- to_int_prog :: wrap_proto to_int_ml_spec.
  Proof.
    iIntros (fn ws Φ) "H". iNamed "H". iNamedProto "Hproto".
    iSplit; first done. iIntros (Φ'') "HΦ".
    iAssert (⌜length lvs = 1⌝)%I as %Hlen.
    { by iDestruct (big_sepL2_length with "Hsim") as %?. }
    destruct lvs as [|lv []]; try by (exfalso; eauto with lia); []. clear Hlen.
    destruct ws as [|w []]; try by (exfalso; apply Forall2_length in Hrepr; eauto with lia); [].
    apply Forall2_cons_1 in Hrepr as [Hrepr _].
    cbn. iDestruct "Hsim" as "[-> _]".
    wp_call_direct.
    (* p1 = *(((int * * ) Data_custom_val(p))) *)
    wp_apply (wp_read_foreign with "[$HGC $Hγ]"); try eauto.
    iIntros "(HGC&Hγ)". wp_pures.
    (* res = to_int(p1) *)
    wp_extern. iModIntro. iRight. iRight.
    iSplit; first done. iExists n, q, _. iSplit; first done. iFrame "Hq".
    iIntros "!> Hq". wp_pures.
    (* vres = Val_int(ures) *)
    wp_apply (wp_int2val with "HGC"); try eauto.
    iIntros (w') "(HGC&%Hw')".
    iApply "HΦ".
    iApply ("Return" $! θ (OVal _) (OVal (Lint n)) with "[$HGC] [Cont Hγ Hq] []").
    - iApply "Cont". iFrame.
    - cbn. done.
    - iPureIntro. econstructor. eauto.
  Qed.

  Lemma two_correct :
    prims_proto two_ml_spec ⊔ lib_spec
    ||- two_prog :: wrap_proto two_ml_spec.
  Proof.
    iIntros (fn ws Φ) "H". iNamed "H". iNamedProto "Hproto".
    iSplit; first done. iIntros (Φ'') "HΦ".
    iAssert (⌜length lvs = 1⌝)%I as %Hlen.
    { by iDestruct (big_sepL2_length with "Hsim") as %?. }
    destruct lvs as [|lv []]; try by (exfalso; eauto with lia); []. clear Hlen.
    destruct ws as [|w []]; try by (exfalso; apply Forall2_length in Hrepr; eauto with lia); [].
    apply Forall2_cons_1 in Hrepr as [Hrepr _].
    cbn. iDestruct "Hsim" as "[-> _]".
    wp_call_direct.
    (* p1 = Int_val(p) *)
    wp_apply (wp_val2int with "HGC"); try eauto.
    iIntros "HGC". wp_pures.
    (* CAMLlocal3(ret, p_r, p_r1) *)
    wp_apply (wp_CAMLlocal with "HGC"); eauto. iIntros (ℓret) "(HGC&Hret)". wp_pures.
    wp_apply (wp_CAMLlocal with "HGC"); eauto. iIntros (ℓr) "(HGC&Hr)". wp_pures.
    wp_apply (wp_CAMLlocal with "HGC"); eauto. iIntros (ℓr1) "(HGC&Hr1)". wp_pures.
    (* the C locals p2 and p3 *)
    wp_alloc p2 as "Hp2"; first done. wp_pures.
    wp_alloc p3 as "Hp3"; first done. wp_pures.
    change (Z.to_nat 1) with 1. cbn.
    iDestruct "Hp2" as "(Hp2&_)". iDestruct "Hp3" as "(Hp3&_)".
    rewrite !loc_add_0.
    wp_apply (wp_store with "Hp2"). iIntros "Hp2". wp_pures.
    wp_apply (wp_store with "Hp3"). iIntros "Hp3". wp_pures.
    (* initialize_ptr(&p2); initialize_ptr(&p3) *)
    wp_extern. iModIntro. iRight. iLeft. iLeft.
    iSplit; first done. iExists p2, _. iSplit; first done. iFrame "Hp2".
    iIntros "!>" (q1) "(Hp2&Hq1)". wp_pures.
    wp_extern. iModIntro. iRight. iLeft. iLeft.
    iSplit; first done. iExists p3, _. iSplit; first done. iFrame "Hp3".
    iIntros "!>" (q2) "(Hp3&Hq2)". wp_pures.
    (* two(p1, p2, p3) *)
    wp_apply (wp_load with "Hp2"). iIntros "Hp2". wp_pures.
    wp_apply (wp_load with "Hp3"). iIntros "Hp3". wp_pures.
    wp_extern. iModIntro. iRight. iLeft. iRight.
    iSplit; first done. iExists n, q1, q2, _, _. iSplit; first done.
    iFrame "Hq1 Hq2".
    iIntros "!> (Hq1&Hq2)". wp_pures.
    (* camlid_c2ml(&p_r, &p2) *)
    wp_apply (wp_alloc_foreign with "HGC"); try eauto.
    iIntros (θ1 γ1 w1) "(HGC&Hγ1&%Hw1)".
    wp_apply (store_to_root with "[$HGC $Hr]"); first done.
    iIntros "(HGC&Hr)". wp_pures.
    wp_apply (load_from_root with "[$HGC $Hr]"). iIntros (w1') "(Hr&HGC&%Hw1')".
    wp_pures.
    wp_apply (wp_load with "Hp2"). iIntros "Hp2". wp_pures.
    wp_apply (wp_write_foreign with "[$HGC $Hγ1]"); try eauto.
    iIntros "(HGC&Hγ1)". wp_pures.
    (* camlid_c2ml(&p_r1, &p3): allocates, p_r is a root *)
    wp_apply (wp_alloc_foreign with "HGC"); try eauto.
    iIntros (θ2 γ2 w2) "(HGC&Hγ2&%Hw2)".
    wp_apply (store_to_root with "[$HGC $Hr1]"); first done.
    iIntros "(HGC&Hr1)". wp_pures.
    wp_apply (load_from_root with "[$HGC $Hr1]"). iIntros (w2') "(Hr1&HGC&%Hw2')".
    wp_pures.
    wp_apply (wp_load with "Hp3"). iIntros "Hp3". wp_pures.
    wp_apply (wp_write_foreign with "[$HGC $Hγ2]"); try eauto.
    iIntros "(HGC&Hγ2)". wp_pures.
    (* ret = caml_alloc(2,0) *)
    wp_apply (wp_alloc TagDefault with "HGC"); try (eauto with lia).
    iIntros (θ3 γ w3) "(HGC&Hγ&%Hw3)". wp_pures.
    wp_apply (store_to_root with "[$HGC $Hret]"); first done.
    iIntros "(HGC&Hret)". wp_pures.
    (* Store_field(ret, 0, p_r); Store_field(ret, 1, p_r1) *)
    wp_apply (load_from_root with "[$HGC $Hret]"). iIntros (w4) "(Hret&HGC&%Hw4)".
    wp_pures.
    wp_apply (load_from_root with "[$HGC $Hr]"). iIntros (w5) "(Hr&HGC&%Hw5)".
    wp_pures.
    wp_apply (wp_modify with "[$HGC $Hγ]"); try eauto. 1: simpl; done.
    iIntros "(HGC&Hγ)". wp_pures.
    wp_apply (load_from_root with "[$HGC $Hret]"). iIntros (w6) "(Hret&HGC&%Hw6)".
    wp_pures.
    wp_apply (load_from_root with "[$HGC $Hr1]"). iIntros (w7) "(Hr1&HGC&%Hw7)".
    wp_pures.
    wp_apply (wp_modify with "[$HGC $Hγ]"); try eauto. 1: simpl; done.
    iIntros "(HGC&Hγ)". wp_pures.
    (* the C locals go out of scope *)
    wp_apply (wp_free with "Hp2"). iIntros "_". wp_pures.
    wp_apply (wp_free with "Hp3"). iIntros "_". wp_pures.
    (* CAMLreturn(ret) *)
    wp_apply (load_from_root with "[$HGC $Hret]"). iIntros (w8) "(Hret&HGC&%Hw8)".
    wp_pures.
    wp_apply (wp_CAMLunregister1 with "[$HGC $Hret]"); try eauto.
    iIntros "HGC". wp_pures.
    wp_apply (wp_CAMLunregister1 with "[$HGC $Hr]"); try eauto.
    iIntros "HGC". wp_pures.
    wp_apply (wp_CAMLunregister1 with "[$HGC $Hr1]"); try eauto.
    iIntros "HGC". wp_pures.
    iMod (freeze_to_immut γ _ θ3 with "[$]") as "(HGC&#Hγ)".
    iModIntro. iApply "HΦ".
    iApply ("Return" $! θ3 (OVal _) (OVal (Lloc γ)) with "[$HGC] [Cont Hγ1 Hq1 Hγ2 Hq2] []").
    - iApply ("Cont" $! γ1 γ2 q1 q2). iFrame.
    - cbn. iExists γ, (Lloc γ1), (Lloc γ2). iSplit; first done. iFrame "Hγ". done.
    - iPureIntro. econstructor. eauto.
  Qed.

End Stubs.
