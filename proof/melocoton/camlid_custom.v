(** Two stubs generated by camlid, checked in Melocoton.

    The C code is the translation of the stubs that camlid generates for a
    custom type ([tests/custom], with the function [two] added):

    {v
    let pointer =
      custom ~clear:"finalize_ptr" ~compare:"compare_ptr" ~hash:"hash_ptr"
        ~init:"initialize_ptr" ~ml:"myptr" ~c:"int *" ()

    func "to_int" [ input pointer ] ~result:c_int;
    func "two" [ input c_int; output pointer; output pointer ];
    v}

    Translation (λC has no local variables and no [&x]):
    - a C local is a cell allocated with [malloc] and freed at the end;
    - the byte stub ([value] arguments) and the native stub are merged;
    - the static function [camlid_c2ml] is inlined;
    - a custom block is a foreign block of Melocoton. It holds the [int *]
      of the C value. Melocoton has no finalizer: the C memory stays owned
      by the foreign block (our owner [Kept]), forever.

    The C functions of the library are specified by protocols: they are the
    hypotheses on the templates and on the C library. *)

